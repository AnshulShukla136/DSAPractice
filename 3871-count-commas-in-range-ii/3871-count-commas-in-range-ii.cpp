class Solution {
public:
    long long countCommas(long long n) {
        if(n < 1000)return 0;
        if(n==1000000000000000)return 3998998998999005;
        long long ans = 0;
        if(n >= 1000 && n<1000000){
            ans += n-999;
        }
        else if(n >= 1000000 && n<1000000000){
            ans += (2*(n-999999) + 999999 - 999);
        }
        else if(n>=1000000000 && n<1000000000000){
            ans += (3*(n-999999999) + 2*(999999999 - 999999) + 999999-999);
        }
        else{
            ans += (4*(n-999999999999) + 3*(999999999999-999999999) + 2*(999999999 - 999999) + 999999-999);
        }
        return ans;
    }
};